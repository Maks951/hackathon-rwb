"""Export API contracts without loading database, provider or runner integration factories."""

import argparse
import json
from pathlib import Path

from app.api.application import create_app
from app.config import Settings
from app.ports import Runtime
from app.schemas.runs import (
    DeploymentStatus,
    ErrorDto,
    EventDto,
    EventsDto,
    RunDetailsDto,
    RunDto,
    RunStatus,
    StepDto,
    StepStatus,
    ValidationStatus,
)


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    match schema.get("type"):
        case "string":
            return "string"
        case "integer" | "number":
            return "number"
        case "boolean":
            return "boolean"
        case "null":
            return "null"
        case "array":
            item = ts_type(schema["items"])
            return f"({item})[]" if " | " in item else f"{item}[]"
        case "object":
            return f"Record<string, {ts_type(schema['additionalProperties'])}>"
        case _:
            raise ValueError(f"Unsupported schema: {schema}")


def typescript() -> str:
    lines = ["// Generated by python -m app.export_contracts; do not edit manually.", ""]
    for enum in (RunStatus, StepStatus, ValidationStatus, DeploymentStatus):
        values = " | ".join(json.dumps(item.value) for item in enum)
        lines.extend([f"export type {enum.__name__} = {values};", ""])
    for model in (ErrorDto, RunDto, StepDto, RunDetailsDto, EventDto, EventsDto):
        schema = model.model_json_schema(by_alias=True)
        inherited = (
            RunDto.model_json_schema(by_alias=True)["properties"] if model is RunDetailsDto else {}
        )
        extension = " extends RunDto" if model is RunDetailsDto else ""
        lines.append(f"export interface {model.__name__}{extension} {{")
        for name, property_schema in schema["properties"].items():
            if name not in inherited:
                optional = "" if name in schema.get("required", []) else "?"
                lines.append(f"  {name}{optional}: {ts_type(property_schema)};")
        lines.extend(["}", ""])
    return "\n".join(lines)


def export(directory: Path) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    schema = create_app(Settings(_env_file=None), Runtime()).openapi()
    (directory / "platform-openapi.json").write_text(
        json.dumps(schema, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    (directory / "runs.ts").write_text(typescript(), encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, default=Path("../contracts"))
    export(parser.parse_args().output_dir)
